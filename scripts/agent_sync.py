#!/usr/bin/env python3
"""Mirror the working Pi setup (~/.pi/agent) into Claude Code and Codex.

Pi stays the single source of truth. Re-run after changing Pi's AGENTS.md,
APPEND_SYSTEM.md, prompts, skills list or mcp.json:

    megai-agent-sync            # apply
    megai-agent-sync --check    # show what would change, write nothing

What it syncs:
  - instructions: ~/.claude/CLAUDE.md and ~/.codex/AGENTS.md are generated from
    Pi AGENTS.md + APPEND_SYSTEM.md (task-resources markers are preserved)
  - skills: every skill enabled in Pi settings.json is symlinked into
    ~/.claude/skills and ~/.codex/skills (live, no copies)
  - prompts: Pi prompts become Claude commands and Codex skills (/mdev etc.)
  - MCP: Pi mcp.json servers missing in Claude/Codex are added
  - hooks: megai-test-guard (PreToolUse) for both, trusted in Codex; Codex keep-going Stop hook
    gets Pi's current keep-going-core.mjs
Before writing, the previous files are saved in a receipt under
~/.pi/agent/local-change-receipts/agent-sync-<timestamp>/.

Install from the MEGAI repo with `python3 scripts/install_agent_sync.py`
(details: docs/agent-sync.md). A missing `claude` or `codex` CLI skips only the
steps that need it.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
PI = HOME / ".pi/agent"
CLAUDE = HOME / ".claude"
CODEX = HOME / ".codex"
CLAUDE_JSON = HOME / ".claude.json"
HOOKS_SRC = HOME / ".local/share/megai-agent-hooks"
GENERATED = "<!-- Generated by megai-agent-sync from ~/.pi/agent/AGENTS.md + APPEND_SYSTEM.md. Edit the Pi files and re-run `megai-agent-sync`; edits here are overwritten. -->"

PREFACE = """# Shared MEGAI rules ({agent})

These are the user's global rules, shared with Pi. Where a rule names Pi, its
sessions or its runtime, it applies to {agent} the same way. Pi-only mechanics
that do not exist here: the `codemode` tool, Pi extensions (`/factory`,
`/factory-flow`, lean-prompt, budget-guard) and `!!` shell commands. Search
with the `tgrep` CLI through the shell by default, as Pi does:
`tgrep --no-index -nH --no-heading -S -m 5 -F -- PATTERN PATH` for literals
(drop `-F` for regex) and `tgrep --no-index --files --glob GLOB PATH` for
filenames. Never build an index or start `tgrep serve` unless the task asks.
Use `rg` with the same flags only when tgrep is missing or fails. Shared state stays shared:
Brokan MCP, `.pi/project.json` project bindings, the heavy-job slot
`~/.pi/agent/.mac-heavy-test.lock`, and `~/.local/bin/megai-task-resources`.
Pi's skills and the `/mdev`, `/prdev`, `/rwbrowser` prompts are installed here
too.{extra}
"""
EXTRA = {
    "claude": "",
    "codex": "",
}

changes: list[str] = []
BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")


def read_json(path: Path, default):
    return json.loads(path.read_text()) if path.is_file() else default


def toml_key(key: str) -> str:
    return key if BARE_KEY.fullmatch(key) else json.dumps(key)


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.is_file() else "absent"


class Receipt:
    def __init__(self, check: bool):
        self.check = check
        self.dir = PI / "local-change-receipts" / f"agent-sync-{dt.datetime.now():%Y%m%d-%H%M%S}"
        self.manifest: dict = {"createdAt": dt.datetime.now(dt.timezone.utc).isoformat(), "before": {}, "moved": {}}  # noqa: UP017 (runs on macOS python3 3.9)

    def _ensure_dir(self):
        # Receipts may hold copies of files with credentials (config.toml, .claude.json).
        self.dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(self.dir, 0o700)

    def save(self, path: Path):
        if self.check or str(path) in self.manifest["before"]:
            return
        self._ensure_dir()
        self.manifest["before"][str(path)] = sha(path)
        if path.is_file():
            dest = self.dir / "before" / path.relative_to(HOME)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dest)

    def move_aside(self, path: Path):
        self._ensure_dir()
        dest = self.dir / "moved" / path.relative_to(HOME)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(path), dest)
        self.manifest["moved"][str(path)] = str(dest)

    def finish(self):
        if self.check or not (self.manifest["before"] or self.manifest["moved"]):
            return
        self._ensure_dir()
        (self.dir / "manifest.json").write_text(json.dumps(self.manifest, indent=2) + "\n")
        print(f"receipt: {self.dir}")


def write(path: Path, text: str, receipt: Receipt, mode: int | None = None):
    old = path.read_text() if path.is_file() else None
    if old == text:
        return
    changes.append(f"write {path}")
    if receipt.check:
        return
    receipt.save(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".agent-sync.tmp")
    tmp.write_text(text)
    if mode is None and path.exists():
        mode = path.stat().st_mode & 0o777
    if mode is not None:
        os.chmod(tmp, mode)
    os.replace(tmp, path)


# ---------------------------------------------------------------- instructions

def render_instructions(agent: str) -> str:
    agents = (PI / "AGENTS.md").read_text().rstrip()
    append = (PI / "APPEND_SYSTEM.md").read_text().rstrip()
    name = {"claude": "Claude Code", "codex": "Codex"}[agent]
    preface = PREFACE.format(agent=name, extra=EXTRA[agent])
    return f"{GENERATED}\n\n{preface}\n{agents}\n\n{append}\n"


# ---------------------------------------------------------------- skills

def enabled_skills() -> list[str]:
    settings = json.loads((PI / "settings.json").read_text())
    names = []
    for entry in settings.get("skills", []):
        m = re.fullmatch(r"\+skills/([^/]+)/SKILL\.md", entry)
        if m and (PI / "skills" / m.group(1) / "SKILL.md").is_file():
            names.append(m.group(1))
    return names


def same_tree(a: Path, b: Path) -> bool:
    return subprocess.run(["diff", "-rq", str(a), str(b)], capture_output=True, check=False).returncode == 0


def is_subset(old: Path, new: Path) -> bool:
    """Every file in old exists unchanged in new (new may add files)."""
    for f in old.rglob("*"):
        if f.is_file():
            g = new / f.relative_to(old)
            if not g.is_file() or g.read_bytes() != f.read_bytes():
                return False
    return True


def sync_skills(target: Path, names: list[str], receipt: Receipt):
    target.mkdir(parents=True, exist_ok=True)
    pi_skills = (PI / "skills").resolve()
    for name in names:
        src = PI / "skills" / name
        dst = target / name
        if dst.is_symlink():
            if dst.resolve() == src.resolve():
                continue
            changes.append(f"relink {dst}")
            if not receipt.check:
                dst.unlink()
        elif dst.exists():
            if not (same_tree(dst, src) or is_subset(dst, src)):
                print(f"keep: {dst} differs from Pi's copy (not replaced)")
                continue
            changes.append(f"replace {dst} (identical/older copy) with symlink")
            if not receipt.check:
                receipt.move_aside(dst)
        else:
            changes.append(f"link {dst}")
        if not receipt.check:
            dst.symlink_to(src)
    # Drop links to Pi skills that Pi no longer enables.
    for link in target.iterdir():
        if link.is_symlink() and link.name not in names:
            try:
                points_to_pi = Path(os.readlink(link)).resolve().parent == pi_skills
            except OSError:
                points_to_pi = False
            if points_to_pi:
                changes.append(f"unlink stale {link}")
                if not receipt.check:
                    link.unlink()


# ---------------------------------------------------------------- prompts

def parse_prompt(path: Path) -> tuple[dict, str]:
    text = path.read_text()
    meta: dict = {}
    m = re.match(r"---\n(.*?)\n---\n?", text, re.DOTALL)
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
        text = text[m.end():]
    return meta, text.lstrip("\n")


def convert_args(body: str) -> str:
    # Pi bash-style ${@:-default} / $@ -> $ARGUMENTS (Claude and Codex syntax).
    body = re.sub(r"\$\{@:-([^}]*)\}", r"$ARGUMENTS (if no arguments were given: \1)", body)
    return body.replace("${@}", "$ARGUMENTS").replace("$@", "$ARGUMENTS")


def render_prompt(path: Path) -> str:
    meta, body = parse_prompt(path)
    head = ["---"] + [f"{k}: {v}" for k, v in meta.items()] + ["---", ""]
    src = f"<!-- Generated by megai-agent-sync from ~/.pi/agent/prompts/{path.name}; edit the Pi prompt instead. -->"
    return "\n".join(head) + src + "\n\n" + convert_args(body).rstrip() + "\n"


def render_codex_skill(path: Path) -> str:
    """Codex 0.171 exposes slash commands as skills, not ~/.codex/prompts."""
    meta, body = parse_prompt(path)
    name = path.stem
    desc = meta.get("description", name).strip().strip('"')
    body = re.sub(r"\$\{@:-([^}]*)\}", r"what the user named after the command (default: \1)", body)
    body = body.replace("${@}", "the user's arguments").replace("$@", "the user's arguments")
    return (f"---\nname: {name}\ndescription: {json.dumps(f'User-invoked /{name} command (from Pi). {desc}. Use only when the user explicitly invokes /{name} or ${name}.')}\n---\n"
            f"<!-- Generated by megai-agent-sync from ~/.pi/agent/prompts/{path.name}; edit the Pi prompt instead. -->\n\n"
            f"{body.rstrip()}\n")


def sync_prompts(receipt: Receipt):
    for p in sorted((PI / "prompts").glob("*.md")):
        write(CLAUDE / "commands" / p.name, render_prompt(p), receipt)
        write(CODEX / "skills" / p.stem / "SKILL.md", render_codex_skill(p), receipt)
        # Older runs wrote ~/.codex/prompts, which this Codex no longer reads.
        old = CODEX / "prompts" / p.name
        if old.is_file() and "Generated by megai-agent-sync" in old.read_text():
            changes.append(f"remove {old}")
            if not receipt.check:
                receipt.save(old)
                old.unlink()
                if not any(old.parent.iterdir()):
                    old.parent.rmdir()


# ---------------------------------------------------------------- MCP

def pi_mcp() -> dict:
    return read_json(PI / "mcp.json", {}).get("mcpServers", {})


def toml_str(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_str(x) for x in v) + "]"
    return json.dumps(str(v))


def sync_codex_config(receipt: Receipt):
    path = CODEX / "config.toml"
    new = path.read_text() if path.is_file() else ""
    # Shared rules are ~30 KB; keep them from being truncated.
    if not re.search(r"(?m)^project_doc_max_bytes\s*=", new):
        first_table = re.search(r"(?m)^\[", new)
        line = "project_doc_max_bytes = 65536\n"
        new = new[: first_table.start()] + line + "\n" + new[first_table.start():] if first_table else new + line
    for name, cfg in pi_mcp().items():
        table = f"mcp_servers.{toml_key(name)}"
        if re.search(rf"(?m)^\[{re.escape(table)}\]", new) or not cfg.get("command"):
            continue
        block = [f"\n[{table}]", f"command = {toml_str(cfg['command'])}"]
        if cfg.get("args"):
            block.append(f"args = {toml_str(cfg['args'])}")
        if cfg.get("timeout"):
            block.append(f"tool_timeout_sec = {float(cfg['timeout'])}")
        if cfg.get("env"):
            block.append(f"\n[{table}.env]")
            block += [f"{toml_key(k)} = {toml_str(v)}" for k, v in cfg["env"].items()]
        new = new.rstrip("\n") + "\n" + "\n".join(block) + "\n"
    write(path, new, receipt, mode=0o600)


def sync_claude_mcp(receipt: Receipt):
    have = read_json(CLAUDE_JSON, {}).get("mcpServers", {})
    for name, cfg in pi_mcp().items():
        if name in have or not cfg.get("command"):
            continue
        if not shutil.which("claude"):
            print(f"warn: claude CLI not found; MCP server {name} not added to Claude")
            continue
        spec = {"type": "stdio", "command": cfg["command"], "args": cfg.get("args", [])}
        if cfg.get("env"):
            spec["env"] = cfg["env"]
        changes.append(f"claude mcp add {name} (user scope)")
        if not receipt.check:
            receipt.save(CLAUDE_JSON)
            done = subprocess.run(["claude", "mcp", "add-json", "-s", "user", name, json.dumps(spec)],
                                  capture_output=True, text=True, check=False)
            if done.returncode:
                print(f"warn: claude mcp add-json {name} failed: {done.stderr.strip()[:200]}")


# ---------------------------------------------------------------- hooks + Claude settings

HOOK_PATH = 'PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"'
CODEX_KEEP_GOING_CMD = f'{HOOK_PATH} node "$HOME/.codex/hooks/megai-keep-going.mjs"'


def hook_cmd(script: str) -> str:
    return f'{HOOK_PATH} node "$HOME/.local/share/megai-agent-hooks/{script}"'


# Codex hooks this script may trust: exact commands only, never a substring match.
MANAGED_CODEX_HOOKS = {hook_cmd("test-guard.mjs"), CODEX_KEEP_GOING_CMD}


def ensure_hook(hooks: dict, event: str, matcher: str | None, command: str, timeout: int):
    groups = hooks.setdefault(event, [])
    for g in groups:
        for h in g.get("hooks", []):
            if h.get("command") == command:
                return
    group: dict = {"hooks": [{"type": "command", "command": command, "timeout": timeout}]}
    if matcher:
        group = {"matcher": matcher, **group}
    groups.append(group)


def sync_claude_settings(receipt: Receipt):
    path = CLAUDE / "settings.json"
    data = read_json(path, {})
    # Pi exposes figma-console (deferred); Claude defers MCP tools too, so allow it.
    denied = [d for d in data.get("deniedMcpServers", []) if d.get("serverName") not in pi_mcp()]
    if denied:
        data["deniedMcpServers"] = denied
    else:
        data.pop("deniedMcpServers", None)
    hooks = data.setdefault("hooks", {})
    # Pi's keep-going applies to GPT models only by default, so Claude gets no Stop hook.
    ensure_hook(hooks, "PreToolUse", "Bash", hook_cmd("test-guard.mjs"), 30)
    write(path, json.dumps(data, indent=2) + "\n", receipt)


def codex_hooks_list() -> list[dict]:
    """Ask `codex app-server` for user hooks with their current hash and trust status."""
    import select
    import time
    proc = subprocess.Popen(["codex", "app-server"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL, text=True)
    try:
        def send(msg):
            proc.stdin.write(json.dumps(msg) + "\n")
            proc.stdin.flush()

        def recv(want, timeout=30):
            end = time.time() + timeout
            while time.time() < end:
                ready, _, _ = select.select([proc.stdout], [], [], 1)
                if ready:
                    line = proc.stdout.readline()
                    if not line:
                        return None
                    msg = json.loads(line)
                    if msg.get("id") == want:
                        return msg
            return None

        send({"id": 1, "method": "initialize", "params": {"clientInfo": {"name": "megai-agent-sync", "version": "1"}}})
        recv(1)
        send({"method": "initialized"})
        send({"id": 2, "method": "hooks/list", "params": {"cwds": [str(HOME)]}})
        res = recv(2) or {}
        return [h for d in res.get("result", {}).get("data", []) for h in d.get("hooks", [])]
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()


def trust_codex_hooks(receipt: Receipt):
    """Codex runs a hook only after its hash is trusted ([hooks.state] in config.toml).
    Trust exactly the MEGAI hooks this script manages, at their current hash."""
    if not shutil.which("codex"):
        print("warn: codex CLI not found; Codex hook trust not checked")
        return
    try:
        hooks = codex_hooks_list()
    except (OSError, ValueError) as exc:
        print(f"warn: could not read Codex hook trust ({exc}); run /hooks in Codex to trust them")
        return
    path = CODEX / "config.toml"
    text = path.read_text() if path.is_file() else ""
    for h in hooks:
        ours = h.get("sourcePath") == str(CODEX / "hooks.json") and h.get("command") in MANAGED_CODEX_HOOKS
        if not ours or h.get("trustStatus") == "trusted" or not h.get("currentHash"):
            continue
        if receipt.check:
            changes.append(f"trust Codex hook {h['key']}")
            continue
        header = f'[hooks.state.{json.dumps(h["key"])}]'
        block = f'{header}\ntrusted_hash = {json.dumps(h["currentHash"])}\n'
        pattern = re.compile(rf"(?m)^{re.escape(header)}\n(?:(?!\[).*\n?)*")
        text = pattern.sub(block + "\n", text) if pattern.search(text) else text.rstrip("\n") + "\n\n" + block
    write(path, text, receipt, mode=0o600)


def sync_codex_hooks(receipt: Receipt):
    path = CODEX / "hooks.json"
    data = read_json(path, {"hooks": {}})
    data["description"] = "MEGAI (synced from Pi): keep-going Stop hook and test-weakening push guard."
    hooks = data.setdefault("hooks", {})
    ensure_hook(hooks, "PreToolUse", None, hook_cmd("test-guard.mjs"), 30)
    write(path, json.dumps(data, indent=2) + "\n", receipt)
    # In --check mode hooks.json may not be written yet, so trust is read from the current file.
    trust_codex_hooks(receipt)
    core = PI / "extensions/megai-keep-going/keep-going-core.mjs"
    if (CODEX / "hooks/megai-keep-going.mjs").exists() and core.exists():
        write(CODEX / "hooks/keep-going-core.mjs", core.read_text(), receipt)


# ---------------------------------------------------------------- main

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="show changes, write nothing")
    args = ap.parse_args(argv)
    names: list[str] = []
    for need in (PI / "AGENTS.md", PI / "APPEND_SYSTEM.md", PI / "settings.json", HOOKS_SRC / "test-guard.mjs"):
        if not need.exists():
            sys.exit(f"missing {need}")
    receipt = Receipt(args.check)
    try:
        write(CLAUDE / "CLAUDE.md", render_instructions("claude"), receipt)
        write(CODEX / "AGENTS.md", render_instructions("codex"), receipt)
        names = enabled_skills()
        sync_skills(CLAUDE / "skills", names, receipt)
        sync_skills(CODEX / "skills", names, receipt)
        sync_prompts(receipt)
        sync_codex_config(receipt)
        sync_claude_mcp(receipt)
        sync_claude_settings(receipt)
        sync_codex_hooks(receipt)
    finally:
        receipt.finish()
    print("\n".join(changes) if changes else "in sync")
    print(f"{len(changes)} change(s){' (check only)' if args.check else ''}; skills enabled in Pi: {len(names)}")


if __name__ == "__main__":
    main()
